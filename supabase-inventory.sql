CREATE OR REPLACE FUNCTION public.auto_assign_unassigned_shipments()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    pending_shipment record;
    selected_vehicle_id uuid;
    previous_dispatch_setting text;
BEGIN
    previous_dispatch_setting := current_setting('app.auto_dispatch', true);
    PERFORM set_config('app.auto_dispatch', 'on', true);

    UPDATE public.vehicle_locations AS vehicles
    SET status = 'Available'
    WHERE vehicles.status = 'On Delivery'
      AND NOT EXISTS (
          SELECT 1
          FROM public.shipments AS assigned_shipments
          WHERE assigned_shipments.vehicle_id = vehicles.vehicle_id
            AND assigned_shipments.status <> 'Delivered'
      );

    UPDATE public.vehicle_locations AS vehicles
    SET status = 'On Delivery'
    WHERE vehicles.status = 'Available'
      AND EXISTS (
          SELECT 1
          FROM public.shipments AS assigned_shipments
          WHERE assigned_shipments.vehicle_id = vehicles.vehicle_id
            AND assigned_shipments.status <> 'Delivered'
      );

    FOR pending_shipment IN
        SELECT shipments.id,
               shipments.destination_latitude,
               shipments.destination_longitude
        FROM public.shipments AS shipments
        WHERE shipments.vehicle_id IS NULL
          AND shipments.destination_latitude IS NOT NULL
          AND shipments.destination_longitude IS NOT NULL
          AND shipments.status <> 'Delivered'
        ORDER BY shipments.created_at, shipments.id
        FOR UPDATE OF shipments SKIP LOCKED
    LOOP
        selected_vehicle_id := NULL;

        SELECT vehicles.vehicle_id
        INTO selected_vehicle_id
        FROM public.vehicle_locations AS vehicles
        WHERE vehicles.status = 'Available'
          AND vehicles.assigned_driver_id IS NOT NULL
          AND vehicles.latitude IS NOT NULL
          AND vehicles.longitude IS NOT NULL
          AND NOT EXISTS (
              SELECT 1
              FROM public.shipments AS assigned_shipments
              WHERE assigned_shipments.vehicle_id = vehicles.vehicle_id
                AND assigned_shipments.status <> 'Delivered'
          )
        ORDER BY 6371 * 2 * asin(
            sqrt(LEAST(
                1.0,
                power(
                    sin(radians(
                        vehicles.latitude -
                        pending_shipment.destination_latitude
                    ) / 2),
                    2
                ) +
                cos(radians(pending_shipment.destination_latitude)) *
                cos(radians(vehicles.latitude)) *
                power(
                    sin(radians(
                        vehicles.longitude -
                        pending_shipment.destination_longitude
                    ) / 2),
                    2
                )
            ))
        )
        LIMIT 1
        FOR UPDATE OF vehicles SKIP LOCKED;

        IF selected_vehicle_id IS NOT NULL THEN
            UPDATE public.shipments
            SET vehicle_id = selected_vehicle_id
            WHERE id = pending_shipment.id
              AND vehicle_id IS NULL;

            UPDATE public.vehicle_locations
            SET status = 'On Delivery'
            WHERE vehicle_id = selected_vehicle_id
              AND status = 'Available';
        END IF;
    END LOOP;

    PERFORM set_config(
        'app.auto_dispatch',
        COALESCE(previous_dispatch_setting, ''),
        true
    );
END;
$$;

