        assigned_role := 'admin';
    ELSIF NEW.raw_user_meta_data ->> 'app_role' = 'driver' THEN
        assigned_role := 'driver';
    ELSE
        assigned_role := 'supplier';
    END IF;

    INSERT INTO public.user_roles AS existing_role (user_id, email, role)
