CREATE OR REPLACE FUNCTION public.prevent_driver_shipment_changes()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
    IF current_setting('app.auto_dispatch', true) IS DISTINCT FROM 'on'
       AND NOT public.has_app_role('admin')
       AND (to_jsonb(NEW) - ARRAY[
               'status',
               'estimated_delivery_at',
               'delivery_proof_path'
           ])
           IS DISTINCT FROM
           (to_jsonb(OLD) - ARRAY[
               'status',
               'estimated_delivery_at',
               'delivery_proof_path'
           ])
    THEN
        RAISE EXCEPTION 'Drivers may only update status and ETA for their assigned packages.';
    END IF;
    IF public.has_app_role('driver')
       AND current_setting('app.auto_dispatch', true) IS DISTINCT FROM 'on'
       AND (
           (
               NEW.delivery_proof_path IS DISTINCT FROM OLD.delivery_proof_path
               AND (
                   NEW.status <> 'Delivered'
                   OR NEW.delivery_proof_path IS NULL
                   OR NEW.delivery_proof_path NOT LIKE
                       auth.uid()::text || '/' || NEW.id::text || '/%'
               )
           )
           OR (
               NEW.status = 'Delivered'
               AND OLD.status <> 'Delivered'
               AND NEW.delivery_proof_path IS NULL
           )
       )
    THEN
        RAISE EXCEPTION 'Drivers must upload proof of delivery before marking a package delivered.';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS prevent_driver_shipment_changes ON public.shipments;
CREATE TRIGGER prevent_driver_shipment_changes
