CREATE OR REPLACE FUNCTION public.adjust_product_stock(
    p_product_id bigint,
    p_type text,
    p_quantity integer
)
RETURNS TABLE (previous_stock integer, new_stock integer)
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Sign in to adjust product stock.';
    END IF;

    IF p_type IS NULL
        OR p_type NOT IN ('in', 'out')
        OR p_quantity IS NULL
        OR p_quantity <= 0
    THEN
        RAISE EXCEPTION 'Stock type must be in or out and quantity must be positive.';
    END IF;

    SELECT products.stock
    INTO previous_stock
    FROM public.products AS products
    WHERE products.id = p_product_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product not found.';
    END IF;

    new_stock := CASE
        WHEN p_type = 'in' THEN previous_stock + p_quantity
        ELSE previous_stock - p_quantity
    END;

    IF new_stock < 0 THEN
        RAISE EXCEPTION 'Not enough stock available.';
    END IF;

    UPDATE public.products AS products
    SET stock = new_stock
    WHERE products.id = p_product_id;

    RETURN NEXT;
END;
$$;

