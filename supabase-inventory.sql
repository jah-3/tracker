SET search_path = ''
AS $$
BEGIN
    IF current_setting('app.auto_dispatch', true) IS DISTINCT FROM 'on'
       AND NOT public.has_app_role('admin')
       AND (
           NEW.id IS DISTINCT FROM OLD.id
           OR NEW.vehicle_id IS DISTINCT FROM OLD.vehicle_id
           OR NEW.plate_number IS DISTINCT FROM OLD.plate_number
           OR NEW.driver IS DISTINCT FROM OLD.driver
           OR NEW.status IS DISTINCT FROM OLD.status
           OR NEW.item_name IS DISTINCT FROM OLD.item_name
           OR NEW.quantity IS DISTINCT FROM OLD.quantity
           OR NEW.estimated_delivery_at IS DISTINCT FROM OLD.estimated_delivery_at
           OR NEW.assigned_driver_id IS DISTINCT FROM OLD.assigned_driver_id
       )
    THEN
        RAISE EXCEPTION 'Drivers may only update their assigned vehicle GPS location.';
    END IF;
    RETURN NEW;
END;
$$;

